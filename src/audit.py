"""Checkpoint 1 data audit. Reads data/processed/matches.csv (run src/data.py first).

Prints and saves reports/checkpoint1_tables.md. Anomalies are reported, never fixed.
"""
from difflib import SequenceMatcher
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd

from data import ODDS, OUT_PATH, load_all

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "checkpoint1_tables.md"
CLASSES = ["H", "D", "A"]
TEST_SEASONS = ["2023/24", "2024/25", "2025/26"]
BOOKS = {"B365": ["B365H", "B365D", "B365A"],
         "Avg": ["AvgH", "AvgD", "AvgA"],
         "PS": ["PSH", "PSD", "PSA"]}

out: list[str] = []


def emit(s: str = "") -> None:
    print(s)
    out.append(s)


def table(df: pd.DataFrame, index: bool = True, floatfmt: str = "{:.4f}") -> None:
    """Emit a DataFrame as a GitHub markdown table."""
    d = df.rename_axis(df.index.name or "Season").reset_index() if index else df
    emit("| " + " | ".join(map(str, d.columns)) + " |")
    emit("|" + "|".join("---" for _ in d.columns) + "|")
    for _, r in d.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) and not pd.isna(v)
                 else ("" if (not isinstance(v, str) and pd.isna(v)) else str(v)) for v in r]
        emit("| " + " | ".join(cells) + " |")
    emit()


def log_loss(P: np.ndarray, y: np.ndarray) -> float:
    """Mean negative natural-log probability assigned to the realised class."""
    return float(-np.mean(np.log(P[np.arange(len(y)), y])))


def brier(P: np.ndarray, y: np.ndarray) -> float:
    """Multiclass Brier score: mean over matches of sum_k (p_k - 1[y=k])^2."""
    Y = np.eye(3)[y]
    return float(np.mean(np.sum((P - Y) ** 2, axis=1)))


def main() -> None:
    df = pd.read_csv(OUT_PATH, parse_dates=["Date"]) if OUT_PATH.exists() else load_all()
    seasons = sorted(df["Season"].unique())
    odds_cols = [c for c in ODDS if c in df.columns]

    emit("# Checkpoint 1: data audit tables\n")
    emit(f"Source: `{OUT_PATH.relative_to(ROOT)}` ({len(df)} matches). Generated by `src/audit.py`.\n")

    # 1. rows and date range
    emit("## 1. Rows and date range per season\n")
    g = df.groupby("Season")["Date"].agg(rows="size", first="min", last="max")
    g["first"], g["last"] = g["first"].dt.date, g["last"].dt.date
    g["status"] = np.where(g["rows"] == 380, "complete", "PARTIAL/ANOMALY")
    table(g)

    # 2. missing values
    emit("## 2. Missing values per column per season (count of NaN)\n")
    miss = df.set_index("Season").isna().groupby(level=0).sum()
    miss = miss.loc[:, (miss > 0).any() | miss.columns.isin(["Date", "FTHG", "FTAG", "FTR"])]
    table(miss.astype(int))
    emit("Columns with no missing values anywhere are omitted, except Date and the result columns.\n")
    emit("Odds columns present in the processed table but entirely absent for a season "
         "(count = rows in that season) are a property of the source files, not of the loader.\n")

    # 3. sanity checks
    emit("## 3. Sanity checks\n")
    res = np.sign(df["FTHG"] - df["FTAG"]).map({1: "H", 0: "D", -1: "A"})
    bad = df[res != df["FTR"]]
    emit(f"- FTR inconsistent with FTHG/FTAG: **{len(bad)}** rows")
    if len(bad):
        table(bad[["Season", "Date", "HomeTeam", "AwayTeam", "FTHG", "FTAG", "FTR"]], index=False)
    dup = df[df.duplicated(["Date", "HomeTeam", "AwayTeam"], keep=False)]
    emit(f"- Duplicate (Date, Home, Away) rows: **{len(dup)}**")
    dup2 = df[df.duplicated(["Season", "HomeTeam", "AwayTeam"], keep=False)]
    emit(f"- Same fixture twice in one season (Season, Home, Away): **{len(dup2)}**")
    selfp = (df["HomeTeam"] == df["AwayTeam"]).sum()
    emit(f"- Home team == away team: **{selfp}**")
    emit(f"- Negative or non-integer goals: **{int(((df.FTHG < 0) | (df.FTAG < 0) | (df.FTHG % 1 != 0) | (df.FTAG % 1 != 0)).sum())}**")
    emit(f"- Dates unsorted after load: **{int((df['Date'].diff().dt.days < 0).sum())}**")
    emit("")
    tc = df.groupby("Season").apply(lambda x: len(set(x.HomeTeam) | set(x.AwayTeam)),
                                    include_groups=False)
    hc = df.groupby("Season").apply(lambda x: x.groupby("HomeTeam").size().agg(["min", "max"]).tolist(),
                                    include_groups=False)
    t = pd.DataFrame({"teams": tc, "home games per team (min,max)": hc.map(tuple)})
    t["status"] = np.where(t["teams"] == 20, "ok", "ANOMALY")
    emit("Teams per season (expected 20; each team should have 19 home games in a full season):\n")
    table(t)

    # 4. teams per season, promotion/relegation, spelling
    emit("## 4. Teams, promotion/relegation, spelling\n")
    teams = {s: set(df.loc[df.Season == s, "HomeTeam"]) | set(df.loc[df.Season == s, "AwayTeam"])
             for s in seasons}
    for s in seasons:
        emit(f"- **{s}** ({len(teams[s])}): {', '.join(sorted(teams[s]))}")
    emit("\nChanges between consecutive seasons "
         "(entered = in new season only, left = in previous season only):\n")
    rows = []
    for a, b in zip(seasons, seasons[1:]):
        rows.append({"from": a, "to": b,
                     "left (relegated)": ", ".join(sorted(teams[a] - teams[b])) or "-",
                     "entered (promoted)": ", ".join(sorted(teams[b] - teams[a])) or "-",
                     "n_left": len(teams[a] - teams[b]), "n_entered": len(teams[b] - teams[a])})
    ch = pd.DataFrame(rows)
    table(ch, index=False)
    flag = ch[(ch.n_left != 3) | (ch.n_entered != 3)]
    if len(flag):
        emit("**Anomaly:** the following transitions do not have exactly 3 in / 3 out "
             "(expected for 20-team promotion/relegation; a partial season can also cause this):\n")
        table(flag[["from", "to", "n_left", "n_entered"]], index=False)
    else:
        emit("All transitions have exactly 3 teams in and 3 out.\n")
    allnames = sorted(set().union(*teams.values()))
    emit(f"All {len(allnames)} distinct team names. Pairs that are textually similar "
         "(possible spelling variants of one club) are listed below; none are merged by the loader:\n")
    sim = [(a, b, SequenceMatcher(None, a.lower(), b.lower()).ratio())
           for a, b in combinations(allnames, 2)]
    sim = [(a, b, r) for a, b, r in sim
           if r >= 0.7 or a.lower() in b.lower() or b.lower() in a.lower()]
    if sim:
        for a, b, r in sorted(sim, key=lambda x: -x[2]):
            both = [s for s in seasons if a in teams[s] and b in teams[s]]
            emit(f"- `{a}` vs `{b}` (similarity {r:.2f}); appear in same season: {'yes ' + str(both) if both else 'no'}")
    else:
        emit("- none found")
    emit("")
    appear = pd.Series({n: sum(n in teams[s] for s in seasons) for n in allnames}).sort_values()
    emit("Names appearing in only one season (check these are real promotions, not renamings):\n")
    emit(", ".join(f"{n} ({[s for s in seasons if n in teams[s]][0]})" for n in appear[appear == 1].index) or "none")
    emit("")

    # 5. class frequencies and goals
    emit("## 5. Class frequencies and mean goals\n")
    freq = pd.crosstab(df["Season"], df["FTR"], normalize="index")[CLASSES]
    freq["n"] = df.groupby("Season").size()
    goals = df.groupby("Season")[["FTHG", "FTAG"]].mean().rename(
        columns={"FTHG": "mean home goals", "FTAG": "mean away goals"})
    tot = pd.DataFrame({**{c: [(df.FTR == c).mean()] for c in CLASSES}, "n": [len(df)]}, index=["ALL"])
    tg = pd.DataFrame({"mean home goals": [df.FTHG.mean()], "mean away goals": [df.FTAG.mean()]}, index=["ALL"])
    table(pd.concat([pd.concat([freq, goals], axis=1), pd.concat([tot, tg], axis=1)]).rename(
        columns={"H": "P(home)", "D": "P(draw)", "A": "P(away)"}))
    emit("Season 2026/27 is partial and is excluded from baselines. 2020/21 (closed doors) "
         "is the one to look at for a home-advantage dip.\n")

    # 6. baselines
    emit("## 6. Baselines on 2023/24 - 2025/26\n")
    emit("Log loss is the mean natural-log loss; Brier is the multiclass sum-of-squares form "
         "(range 0 to 2). Accuracy is the share of matches whose argmax class matches FTR.\n")
    train = df[~df.Season.isin(TEST_SEASONS + ["2026/27"])]
    test = df[df.Season.isin(TEST_SEASONS)].copy()
    y = test["FTR"].map({c: i for i, c in enumerate(CLASSES)}).to_numpy()
    emit(f"Train (for class frequencies): {train.Season.min()} to {train.Season.max()}, "
         f"{len(train)} matches. Test: {len(test)} matches.\n")
    q = train["FTR"].value_counts(normalize=True)[CLASSES].to_numpy()
    emit(f"Training class frequencies: H={q[0]:.4f}, D={q[1]:.4f}, A={q[2]:.4f}\n")

    def row(name, P, yy):
        return {"model": name, "n": len(yy), "log loss": log_loss(P, yy),
                "Brier": brier(P, yy), "accuracy": float((P.argmax(1) == yy).mean())}

    results = [row("uniform 1/3 each", np.full((len(y), 3), 1 / 3), y),
               row("training class frequencies", np.tile(q, (len(y), 1)), y),
               row("always predict home win", np.tile([1 - 2e-9, 1e-9, 1e-9], (len(y), 1)), y)]
    results[-1]["log loss"] = float("nan")  # degenerate: unbounded loss on any non-home result
    results[-1]["Brier"] = float("nan")
    overr = []
    for name, cols in BOOKS.items():
        sub = test.dropna(subset=cols)
        if len(sub) == 0:
            continue
        inv = 1.0 / sub[cols].to_numpy()
        overr.append({"book": name, "n": len(sub), "mean overround (sum 1/odds)": inv.sum(1).mean()})
        P = inv / inv.sum(1, keepdims=True)
        ys = sub["FTR"].map({c: i for i, c in enumerate(CLASSES)}).to_numpy()
        results.append(row(f"bookmaker {name}, overround removed", P, ys))
    common = test.dropna(subset=sum(BOOKS.values(), []))
    if len(common) and len(common) < len(test):
        yc = common["FTR"].map({c: i for i, c in enumerate(CLASSES)}).to_numpy()
        results.append(row("training class freqs (common-odds subset)", np.tile(q, (len(yc), 1)), yc))
        for name, cols in BOOKS.items():
            inv = 1.0 / common[cols].to_numpy()
            results.append(row(f"bookmaker {name} (common-odds subset)", inv / inv.sum(1, keepdims=True), yc))
    table(pd.DataFrame(results), index=False)
    emit("'Always predict home win' is a hard prediction: its accuracy is the home-win rate; "
         "its log loss is unbounded (infinite) because draws and away wins get probability 0, "
         "so it is left blank.\n")
    emit("Bookmaker margin (mean sum of 1/odds before normalising):\n")
    table(pd.DataFrame(overr), index=False)
    emit("Rows with missing odds in the test window are dropped per bookmaker (n shown). "
         "The 'common-odds subset' rows compare all sources on identical matches.\n")

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out) + "\n")
    print(f"\nsaved -> {REPORT}")


if __name__ == "__main__":
    main()
